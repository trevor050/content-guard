/**
 * Measures the last 0.3.x release on the same data as bench/run.ts, so the README
 * can show what the rewrite changed. Optional and slow; needs a one-time install:
 *
 *   npm --prefix bench/legacy install     # ~350 MB, git-ignored
 *   npm run bench:legacy
 *
 * Civil Comments is subsampled (seeded) because 0.3.1 is slow; content-guard is
 * scored on the identical subsample.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { performance } from 'node:perf_hooks'
import { createGuard } from '../src/index.ts'
import { type Example, loadCivilComments, loadSmsSpam, loadStackExchange } from './datasets.ts'
import { TRANSFORM_NAMES, TRANSFORMS } from './obfuscate.ts'

const require = createRequire(new URL('./legacy/package.json', import.meta.url))
const legacy = require('content-guard') as {
  ContentGuard: new (preset: string) => { analyze(text: string): Promise<{ isSpam: boolean }> }
  createGuard: (variant: string) => { analyze(text: string): Promise<{ isSpam: boolean }> }
}
const legacyVersion = (require('content-guard/package.json') as { version: string }).version

type AsyncClassifier = (text: string) => Promise<boolean>

const silence = async <T,>(fn: () => Promise<T>): Promise<T> => {
  // 0.3.1 logs to the console from inside analyze(); keep the report readable.
  const { log, warn, info } = console
  console.log = console.warn = console.info = () => {}
  try {
    return await fn()
  } finally {
    Object.assign(console, { log, warn, info })
  }
}

async function evaluate(classify: AsyncClassifier, examples: readonly Example[]) {
  let tp = 0, fp = 0, fn = 0, tn = 0
  const start = performance.now()
  for (const { text, label } of examples) {
    const predicted = await silence(() => classify(text))
    if (predicted && label) tp++
    else if (predicted) fp++
    else if (label) fn++
    else tn++
  }
  const ms = (performance.now() - start) / examples.length
  const precision = tp + fp ? tp / (tp + fp) : 0
  const recall = tp + fn ? tp / (tp + fn) : 0
  return { precision, recall, f1: precision + recall ? (2 * precision * recall) / (precision + recall) : 0, fpr: fp + tn ? fp / (fp + tn) : 0, ms }
}

function sample<T>(items: readonly T[], count: number, seed: number): T[] {
  let state = seed
  const rand = () => ((state = (Math.imul(state, 1103515245) + 12345) >>> 0) / 2 ** 32)
  const copy = [...items]
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1))
    ;[copy[i], copy[j]] = [copy[j]!, copy[i]!]
  }
  return copy.slice(0, count)
}

const [civil, sms, stack] = await Promise.all([loadCivilComments(), loadSmsSpam(), loadStackExchange()])
const civilSample = sample(civil.split.test, 4000, 42)
const corpus = JSON.parse(readFileSync(new URL('../corpus/adversarial.json', import.meta.url), 'utf8')) as {
  holdout: Record<'toxic' | 'benign', string[]>
}
const advToxic: Example[] = TRANSFORM_NAMES.flatMap((t) => corpus.holdout.toxic.map((s) => ({ text: TRANSFORMS[t](s), label: true })))
const advBenign: Example[] = TRANSFORM_NAMES.flatMap((t) => corpus.holdout.benign.map((s) => ({ text: TRANSFORMS[t](s), label: false })))

const guard = createGuard()
const moderate = new legacy.ContentGuard('moderate')
const balanced = legacy.createGuard('balanced')
const systems: Array<[string, AsyncClassifier]> = [
  ["content-guard 5 (this rewrite)", async (t) => guard.analyze(t).flagged],
  [`content-guard ${legacyVersion}, \`new ContentGuard('moderate')\``, async (t) => (await moderate.analyze(t)).isSpam],
  [`content-guard ${legacyVersion}, \`createGuard('balanced')\``, async (t) => (await balanced.analyze(t)).isSpam],
]

const out: string[] = [
  `# Rewrite vs ${legacyVersion}`,
  '',
  `Generated by \`npm run bench:legacy\`. Node ${process.version}, ${new Date().toISOString().slice(0, 10)}.`,
  `0.3.x returns a single \`isSpam\` flag for everything, so every system here is scored on "flagged at all".`,
  `Civil Comments is a seeded sample of ${civilSample.length.toLocaleString('en-US')} test comments; the other sets are complete test splits.`,
  '',
  '| System | Civil F1 | SMS spam F1 | Benign tech FPR | Adversarial holdout recall | Adversarial holdout FPR | ms / message |',
  '| --- | ---: | ---: | ---: | ---: | ---: | ---: |',
]
for (const [name, classify] of systems) {
  const c = await evaluate(classify, civilSample)
  const s = await evaluate(classify, sms.split.test)
  const t = await evaluate(classify, stack.split.test)
  const a = await evaluate(classify, [...advToxic, ...advBenign])
  const ms = (c.ms * civilSample.length + s.ms * sms.split.test.length + t.ms * stack.split.test.length) / (civilSample.length + sms.split.test.length + stack.split.test.length)
  const row = `| ${name} | ${c.f1.toFixed(3)} | ${s.f1.toFixed(3)} | ${(t.fpr * 100).toFixed(1)}% | ${(a.recall * 100).toFixed(1)}% | ${(a.fpr * 100).toFixed(1)}% | ${ms.toFixed(2)} |`
  out.push(row)
  console.error(row)
}
mkdirSync(new URL('./results/', import.meta.url), { recursive: true })
writeFileSync(new URL('./results/legacy.md', import.meta.url), out.join('\n') + '\n')
console.error('wrote bench/results/legacy.md')
process.exit(0)
