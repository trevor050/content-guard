log(`# content-guard benchmark (${splitName} split)`)
log()
log(`content-guard ${pkg.version}, Node ${process.version}, ${cpus()[0]?.model ?? 'unknown CPU'}, ${new Date().toISOString().slice(0, 10)}.`)
log(`Generated by \`npm run bench${splitName === 'dev' ? ' -- --split dev' : ''}\`. Do not edit by hand.`)
