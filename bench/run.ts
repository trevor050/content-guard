function generateMash(count: number, seed: number): string[] {
  let state = seed
  const rand = () => {
    state = (state + 0x6d2b79f5) | 0
    let t = Math.imul(state ^ (state >>> 15), 1 | state)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
  const rows = ['qwertyuiop', 'asdfghjkl', 'zxcvbnm']
  const walk = (length: number, rowBias: number) => {
    let r = rowBias
    let c = Math.floor(rand() * rows[r]!.length)
    let word = ''
    for (let i = 0; i < length; i++) {
      word += rows[r]![c]
      if (rand() < 0.15) r = Math.min(2, Math.max(0, r + (rand() < 0.5 ? -1 : 1)))
      c = Math.min(rows[r]!.length - 1, Math.max(0, c + Math.floor(rand() * 5) - 2))
    }
    return word
  }
  const results: string[] = []
  for (let i = 0; i < count; i++) {
    const kind = i % 4
    if (kind === 0) results.push(walk(6 + Math.floor(rand() * 10), 1))
    else if (kind === 1) results.push(Array.from({ length: 2 + Math.floor(rand() * 3) }, () => walk(4 + Math.floor(rand() * 6), Math.floor(rand() * 3))).join(' '))
    else if (kind === 2) results.push(walk(3 + Math.floor(rand() * 2), 1).repeat(2 + Math.floor(rand() * 3)))
    else results.push(walk(8 + Math.floor(rand() * 8), Math.floor(rand() * 3)) + (rand() < 0.5 ? '!!' : ''))
  }
  return results
}
