/**
 * Reproducible benchmark for content-guard.
 *
 *   npm run bench                 # report on the held-out test splits, write bench/results/
 *   npm run bench -- --split dev  # numbers on the dev splits (the only ones used for tuning)
 *   npm run bench -- --errors     # also print false positives/negatives for inspection
 *
 * Datasets download on first run (about 45 MB) into bench/.cache/. See bench/datasets.ts.
 */
