const [civil, sms, stack] = await Promise.all([loadCivilComments(), loadSmsSpam(), loadStackExchange()])
const pick = <T,>(s: { dev: T; test: T }) => (splitName === 'dev' ? s.dev : s.test)
const civilEval = pick(civil.split)
const smsEval = pick(sms.split)
const stackEval = pick(stack.split)

const guards = Object.fromEntries([0.3, 0.5, 0.7].map((t) => [t, createGuard({ threshold: t })])) as Record<number, ReturnType<typeof createGuard>>
const cg = (category: Category | 'any', threshold = 0.5): Classifier => {
  const guard = guards[threshold]!
  return category === 'any'
    ? (text) => guard.analyze(text).flagged
    : (text) => guard.analyze(text).scores[category] >= threshold
}

