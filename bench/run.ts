import { createGuard, type Category } from '../src/index.ts'
import { badWords, type Classifier, naiveBayes, obscenity } from './baselines.ts'
import { type DatasetInfo, type Example, loadCivilComments, loadSmsSpam, loadStackExchange } from './datasets.ts'
import { TRANSFORM_NAMES, TRANSFORMS } from './obfuscate.ts'

const args = new Set(process.argv.slice(2))
const splitName = args.has('--split') && process.argv.includes('dev') ? 'dev' : 'test'
const showErrors = args.has('--errors')

interface Metrics {
  n: number
  positives: number
  precision: number
  recall: number
  f1: number
  fpr: number
}

function evaluate(classify: Classifier, examples: readonly Example[]): Metrics & { errors: { fp: string[]; fn: string[] } } {
  let tp = 0, fp = 0, fn = 0, tn = 0
  const errors = { fp: [] as string[], fn: [] as string[] }
  for (const { text, label } of examples) {
    const predicted = classify(text)
    if (predicted && label) tp++
    else if (predicted) { fp++; if (errors.fp.length < 40) errors.fp.push(text) }
    else if (label) { fn++; if (errors.fn.length < 40) errors.fn.push(text) }
    else tn++
  }
  const precision = tp + fp ? tp / (tp + fp) : 0
  const recall = tp + fn ? tp / (tp + fn) : 0
  return {
    n: examples.length,
    positives: tp + fn,
    precision,
    recall,
    f1: precision + recall ? (2 * precision * recall) / (precision + recall) : 0,
    fpr: fp + tn ? fp / (fp + tn) : 0,
    errors,
  }
}

const pct = (x: number) => `${(x * 100).toFixed(1)}%`
const num = (x: number) => x.toFixed(3)
function table(headers: string[], rows: Array<Array<string | number>>): string {
  const line = (cells: Array<string | number>) => `| ${cells.join(' | ')} |`
  return [line(headers), line(headers.map((_, i) => (i === 0 ? '---' : '---:'))), ...rows.map(line)].join('\n')
}

const out: string[] = []
const log = (s = '') => {
  out.push(s)
  console.log(s)
}

