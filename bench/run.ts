log('## Toxicity: Civil Comments')
log()
log(`${civilEval.length.toLocaleString('en-US')} comments, ${pct(civilEval.filter((e) => e.label).length / civilEval.length)} labeled toxic (crowd toxicity score >= 0.5). "Benign tech FPR" is the share of ${stackEval.length} Stack Exchange questions the same classifier flags.`)
log()
const nbToxic = naiveBayes(civil.split.dev)
const toxicSystems: Array<[string, Classifier]> = [
  ['content-guard (threshold 0.3)', cg('toxicity', 0.3)],
  ['**content-guard (default, 0.5)**', cg('toxicity', 0.5)],
  ['content-guard (threshold 0.7)', cg('toxicity', 0.7)],
  ['obscenity 0.4 (word list + transformers)', obscenity()],
  ['bad-words 4 (word list)', badWords()],
  ['Naive Bayes trained on in-domain dev split', nbToxic],
]
const toxicRows = toxicSystems.map(([name, classify]) => {
  const m = evaluate(classify, civilEval)
  const tech = evaluate(classify, stackEval)
  if (showErrors && name.includes('default')) {
    console.error('\n--- toxicity false positives ---\n' + m.errors.fp.slice(0, 25).join('\n---\n'))
    console.error('\n--- toxicity false negatives ---\n' + m.errors.fn.slice(0, 25).join('\n---\n'))
  }
  return [name, num(m.precision), num(m.recall), num(m.f1), pct(m.fpr), pct(tech.fpr)]
})
log(table(['System', 'Precision', 'Recall', 'F1', 'FPR', 'Benign tech FPR'], toxicRows))
log()

