/**
 * Generates src/data/bigrams.ts: an English letter-transition model used by the
 * keyboard-mash detector. Trained on public-domain Project Gutenberg books.
 *
 *   node scripts/gen-bigrams.ts
 *
 * The table holds -log10 P(next | prev) for 27 symbols (a-z plus a word boundary),
 * quantized to steps of 0.2 and encoded as one base-36 character per cell.
 */
import { writeFileSync } from 'node:fs'

const BOOKS = [1342, 84, 1661, 2701, 11] // Pride and Prejudice, Frankenstein, Sherlock Holmes, Moby Dick, Alice
const SYMBOLS = 27 // 0 = boundary, 1..26 = a..z
const counts = Array.from({ length: SYMBOLS }, () => new Float64Array(SYMBOLS))

for (const id of BOOKS) {
  const url = `https://www.gutenberg.org/cache/epub/${id}/pg${id}.txt`
  const res = await fetch(url)
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`)
  const words = (await res.text()).toLowerCase().match(/[a-z]+/g) ?? []
  for (const word of words) {
    let prev = 0
    for (const ch of word) {
      const cur = ch.charCodeAt(0) - 96
      counts[prev]![cur]! += 1
      prev = cur
    }
    counts[prev]![0]! += 1
  }
}

let encoded = ''
for (let i = 0; i < SYMBOLS; i++) {
  const row = counts[i]!
  const total = row.reduce((a, b) => a + b, 0) + SYMBOLS // add-one smoothing
  for (let j = 0; j < SYMBOLS; j++) {
    const cost = -Math.log10((row[j]! + 1) / total)
    encoded += Math.min(35, Math.round(cost / 0.2)).toString(36)
  }
}

const out = `// Generated by scripts/gen-bigrams.ts from public-domain Project Gutenberg books (${BOOKS.join(', ')}). Do not edit.
// 27x27 table of -log10 P(next | prev) in steps of 0.2, one base-36 digit per cell.
// Symbol 0 is a word boundary, 1..26 are a..z.
export const BIGRAM_COSTS = ${JSON.stringify(encoded)}
`
writeFileSync(new URL('../src/data/bigrams.ts', import.meta.url), out)
console.log('wrote bigram table')
