/**
 * Generates src/data/confusables.ts from the Unicode UTS #39 confusables table.
 *
 * We keep only single code points that look like a single ASCII letter and that
 * NFKC normalization does not already fold to ASCII (NFKC runs first at runtime).
 *
 *   node scripts/gen-confusables.ts
 *
 * Source data: Unicode, Inc. (Unicode License v3), https://www.unicode.org/license.txt
 */
import { writeFileSync } from 'node:fs'

const VERSION = '17.0.0'
const SOURCE_URL = `https://www.unicode.org/Public/${VERSION}/security/confusables.txt`

const res = await fetch(SOURCE_URL)
if (!res.ok) throw new Error(`GET ${SOURCE_URL} -> ${res.status}`)
const text = await res.text()

const pairs: Array<[string, string]> = []
for (const line of text.split('\n')) {
  if (!line || line.startsWith('#')) continue
  const [src, dst] = line.split(';').map((s) => s.trim())
  if (!src || !dst || src.includes(' ') || dst.includes(' ')) continue
  const from = String.fromCodePoint(parseInt(src, 16))
  const to = String.fromCodePoint(parseInt(dst, 16))
  if (!/^[A-Za-z]$/.test(to)) continue
  if (from.codePointAt(0)! < 0x80) continue
  if (/^[A-Za-z0-9]+$/.test(from.normalize('NFKC'))) continue
  pairs.push([from, to.toLowerCase()])
}

// Group by target letter to keep the generated file compact and reviewable.
const byTarget = new Map<string, string[]>()
for (const [from, to] of pairs) {
  const list = byTarget.get(to) ?? []
  list.push(from)
  byTarget.set(to, list)
}
const rows = [...byTarget.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([to, froms]) => `  ${to}: ${JSON.stringify(froms.join(''))},`)

const out = `// Generated by scripts/gen-confusables.ts from Unicode ${VERSION} confusables.txt. Do not edit.
// Source: ${SOURCE_URL} (Unicode License v3)
// Each key is an ASCII letter; the value lists code points that are visually confusable with it.
export const CONFUSABLE_SOURCES: Readonly<Record<string, string>> = {
${rows.join('\n')}
}
`
writeFileSync(new URL('../src/data/confusables.ts', import.meta.url), out)
console.log(`wrote ${pairs.length} confusable code points for ${byTarget.size} letters`)
